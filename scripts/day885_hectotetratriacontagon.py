tight_t_max = math.pi / N  # TIGHT_T_MAX
print(f"x at t=0 = {x_at_zero:.6f} = {N}a/{A_OVER_R_FACTOR} (expected {N}*{A}/{A_OVER_R_FACTOR} = {N*A/A_OVER_R_FACTOR:.6f})")
print(f"HECTOTETRATRIACONTAGON_NOTES_HECTOTETRATRIACONTAGON_T_MAX = 2*PI/{N} = {t_max:.6f}")
print(f"HECTOTETRATRIACONTAGON_NOTES_TIGHT_T_MAX = PI/{N} = {tight_t_max:.6f}")

shapes = ['standard', 'inverted', 'hectotetratriacontagon', 'tight']
for shape in shapes:
    finite_count = 0
    for i in range(32):
        t = t_max * i / max(1, 31)
        cosT = math.cos(t)
        sinT = math.sin(t)
        cos133T = math.cos(133 * t)
        sin133T = math.sin(133 * t)
        x = A * cosT + (A / 133) * cos133T
        y = A * sinT - (A / 133) * sin133T
        if math.isfinite(x) and math.isfinite(y):
            finite_count += 1
    print(f"  Shape {shape}: {finite_count}/32 finite samples for 32-sided sample sweep")

# Verify the cusp interval
cusp_deg = 360.0 / N
print(f"\nCusp interval: 360/{N} = {cusp_deg:.4f}° = 2*PI/{N} = {2*math.pi/N:.6f} rad")

